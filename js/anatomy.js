const cordCurve = new THREE.CatmullRomCurve3(CORD_KNOTS.map(([y, z]) => new THREE.Vector3(0, y, z)));
const CORD_LUT = cordCurve.getSpacedPoints(600);
export function cordZ(y) {
  for (let i = 1; i < CORD_LUT.length; i++) {
    const a = CORD_LUT[i - 1], b = CORD_LUT[i];
    if (y <= a.y && y >= b.y) return lerp(a.z, b.z, (a.y - y) / (a.y - b.y || 1));
  }
  return y > CORD_LUT[0].y ? CORD_LUT[0].z : CORD_LUT[CORD_LUT.length - 1].z;
}

