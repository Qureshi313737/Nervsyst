/** Points along rib i (1-12) for side s. */
export function ribPoints(i, s, { yOff = 0, scale = 1, from, to, steps = 16 } = {}) {
  const [rx, rz, cz, drop, tEnd] = RIBS[i - 1];
  const t0 = ribStart(i);
  const a = from ?? t0, b = to ?? tEnd;
  const yb = VY[`T${i}`] + yOff;
  const pts = [];
  for (let k = 0; k <= steps; k++) {
    const th = a + ((b - a) * k) / steps;
    const f = (th - t0) / (Math.PI - t0);
    pts.push([s * rx * scale * Math.sin(th), yb - drop * f, cz - rz * scale * Math.cos(th)]);
  }
  return pts;
}

/** Sympathetic chain position at height y. */
export function trunkPoint(y, s) {
  const k = (knots) => {
    for (let i = 1; i < knots.length; i++) {
      const [y0, v0] = knots[i - 1], [y1, v1] = knots[i];
      if (y <= y0 && y >= y1) return lerp(v0, v1, (y0 - y) / (y0 - y1));
    }
    return knots[y > knots[0][0] ? 0 : knots.length - 1][1];
  };
  const x = k([[15.2, 0.3], [13.8, 0.33], [11.0, 0.3], [10.4, 0.24], [9.3, 0.22], [8.32, 0.0]]);
  const off = k([[15.2, 0.3], [13.8, 0.3], [11.0, 0.24], [10.4, 0.42], [9.4, 0.42], [9.1, 0.3], [8.32, 0.1]]);
  return [s * x, y, cordZ(y) + off];
}

